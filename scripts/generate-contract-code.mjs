#!/usr/bin/env node
/**
 * Generate TypeScript constants from the vendored contract.
 *
 *   contract/semconv.json  ->  src/semconv.generated.ts
 *   contract/metrics.json  ->  src/metrics.generated.ts
 *
 * Attribute names, metric names, units, kinds and histogram bucket boundaries
 * are never typed by hand in this repository: they are generated from what the
 * Python reference implementation was observed to emit. Bumping the pinned tag
 * regenerates them, and a name that disappeared upstream stops compiling here.
 *
 * Runs before build, test, typecheck and lint. The outputs are not committed.
 *
 *   node scripts/generate-contract-code.mjs           write the files
 *   node scripts/generate-contract-code.mjs --check   exit 1 if they are stale
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (path) => JSON.parse(readFileSync(join(ROOT, path), 'utf8'));

const manifest = readJson('contract/MANIFEST.json');
const semconv = readJson('contract/semconv.json');
const metrics = readJson('contract/metrics.json');

const header = (source) =>
  `// GENERATED by scripts/generate-contract-code.mjs from ${source}\n` +
  `// (genai_otel_instrument ${manifest.python_tag}). DO NOT EDIT - run \`npm run generate\`.\n\n`;

/** `gen_ai.request.model` -> `GEN_AI_REQUEST_MODEL` */
function constantName(attribute) {
  return attribute.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
}

function objectLiteral(entries, indent = '  ') {
  return entries.map(([key, value]) => `${indent}${key}: ${JSON.stringify(value)},`).join('\n');
}

function generateSemconv() {
  const constants = Object.entries(semconv.semconv_constants).sort(([a], [b]) => a.localeCompare(b));

  const plain = semconv.attributes.filter((attribute) => !attribute.template);
  const byConstant = new Map();
  for (const attribute of plain) {
    const name = constantName(attribute.name);
    if (!/^[A-Z_][A-Z0-9_]*$/.test(name)) throw new Error(`cannot derive an identifier for ${attribute.name}`);
    if (byConstant.has(name)) {
      throw new Error(`attribute names collide as ${name}: ${byConstant.get(name)} and ${attribute.name}`);
    }
    byConstant.set(name, attribute.name);
  }
  const attributes = [...byConstant.entries()].sort(([a], [b]) => a.localeCompare(b));
  const templates = semconv.attributes
    .filter((attribute) => attribute.template)
    .map((attribute) => attribute.name)
    .sort();
  const superseded = Object.entries(semconv.superseded).sort(([a], [b]) => a.localeCompare(b));

  return (
    header('contract/semconv.json') +
    '/** The constants of `genai_otel.semconv.SemanticConvention`, by the same names. */\n' +
    `export const SemanticConvention = {\n${objectLiteral(constants)}\n} as const;\n\n` +
    '/**\n * Every attribute name the reference implementation writes (templates excluded),\n' +
    ' * keyed by the name in upper snake case. An instrumentor that needs a name not in\n' +
    ' * here does not compile.\n */\n' +
    `export const ATTR = {\n${objectLiteral(attributes)}\n} as const;\n\n` +
    '/** Attribute name patterns; `{placeholders}` are filled in at run time. */\n' +
    `export const ATTR_TEMPLATES = ${JSON.stringify(templates, null, 2)} as const;\n\n` +
    '/** Superseded attribute name -> the current name that carries the same value. */\n' +
    `export const SUPERSEDED_ATTRIBUTES = {\n${objectLiteral(superseded.map(([key, value]) => [JSON.stringify(key), value]))}\n} as const;\n\n` +
    `export const TOKEN_MODALITIES = ${JSON.stringify(semconv.token_modalities)} as const;\n\n` +
    '/** Substrings of `gen_ai.operation.name` that mark an agent invocation. */\n' +
    `export const AGENT_OPERATION_MARKERS = ${JSON.stringify(semconv.agent_operation_markers)} as const;\n\n` +
    `export const STABILITY_OPT_IN_DEFAULT = ${JSON.stringify(semconv.stability_opt_in_default)};\n`
  );
}

function generateMetrics() {
  const definitions = [...metrics.metrics]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(
      (metric) =>
        `  ${JSON.stringify(metric.name)}: {\n` +
        `    name: ${JSON.stringify(metric.name)},\n` +
        `    kind: ${JSON.stringify(metric.kind)},\n` +
        `    unit: ${JSON.stringify(metric.unit)},\n` +
        `    description: ${JSON.stringify(metric.description)},\n` +
        `    meter: ${JSON.stringify(metric.meter)},\n` +
        `    bucketBoundaries: ${JSON.stringify(metric.bucket_boundaries)},\n` +
        `    bucketSource: ${JSON.stringify(metric.bucket_source)},\n` +
        `    requiresGpuDevice: ${JSON.stringify(metric.requires_gpu_device)},\n` +
        '  },',
    )
    .join('\n');

  return (
    header('contract/metrics.json') +
    "export type MetricKind =\n  | 'counter'\n  | 'up_down_counter'\n  | 'histogram'\n  | 'gauge'\n" +
    "  | 'observable_counter'\n  | 'observable_gauge'\n  | 'observable_up_down_counter';\n\n" +
    'export interface MetricDefinition {\n' +
    '  readonly name: string;\n' +
    '  readonly kind: MetricKind;\n' +
    '  /** "" when the reference implementation sets none. */\n' +
    '  readonly unit: string;\n' +
    '  readonly description: string;\n' +
    '  /** Instrumentation scope name. */\n' +
    '  readonly meter: string;\n' +
    '  /** Histograms only. */\n' +
    '  readonly bucketBoundaries: readonly number[] | null;\n' +
    "  /** `view`: set by a View on the meter provider. `sdk_default`: the SDK's default buckets. */\n" +
    "  readonly bucketSource: 'view' | 'sdk_default' | null;\n" +
    '  readonly requiresGpuDevice: boolean;\n' +
    '}\n\n' +
    '/** Every metric instrument the reference implementation creates, by name. */\n' +
    `export const METRIC_DEFINITIONS = {\n${definitions}\n} as const satisfies Record<string, MetricDefinition>;\n\n` +
    'export type MetricName = keyof typeof METRIC_DEFINITIONS;\n\n' +
    "/** The SDK's default explicit bucket boundaries, as observed on the reference implementation. */\n" +
    `export const SDK_DEFAULT_BUCKET_BOUNDARIES = ${JSON.stringify(metrics.sdk_default_bucket_boundaries)} as const;\n`
  );
}

const outputs = [
  ['src/semconv.generated.ts', generateSemconv()],
  ['src/metrics.generated.ts', generateMetrics()],
];

const check = process.argv.includes('--check');
let stale = false;
for (const [path, content] of outputs) {
  const absolute = join(ROOT, path);
  const current = existsSync(absolute) ? readFileSync(absolute, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    stale = true;
    console.error(`${path} is ${current === null ? 'missing' : 'stale'}; run \`npm run generate\``);
  } else {
    writeFileSync(absolute, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
